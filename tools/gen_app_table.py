#!/usr/bin/env python3
"""Generate the built-in application table (kernel image) and the dock launcher catalogue from
apps/<name>/manifest.json. Apps appear in the launcher only if their manifest has a "launcher" object:

  "launcher": {"label": "CAIRN", "subtitle": "Terminal", "accent": "#B9A6FF", "accent2": "#4B3C9A",
               "glyph": ">", "order": 10}

Usage: gen_app_table.py <output.c> <apps-dir> <app> [<app> ...]
Any malformed manifest fails the build (no silent fallbacks)."""
import json, re, sys
from pathlib import Path

HEX = re.compile(r"^#[0-9A-Fa-f]{6}$")


def die(msg):
    print(f"gen_app_table: {msg}", file=sys.stderr)
    sys.exit(1)


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def load(apps_dir, name):
    path = Path(apps_dir) / name / "manifest.json"
    try:
        m = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as e:
        die(f"{path}: {e}")
    for key in ("id", "name", "version"):
        if not isinstance(m.get(key), str) or not m[key]:
            die(f"{path}: missing '{key}'")
    if not re.fullmatch(r"[a-z][a-z0-9]{0,15}", name):
        die(f"{name}: app directory name must be lowercase alphanumeric (<=16)")
    launcher = m.get("launcher")
    if launcher is None:
        return None
    if not isinstance(launcher, dict):
        die(f"{path}: 'launcher' must be an object")
    label = launcher.get("label", m["name"]); sub = launcher.get("subtitle", "")
    if not (isinstance(label, str) and 1 <= len(label) <= 15 and label.isascii() and label.isprintable()):
        die(f"{path}: launcher.label must be 1-15 printable ASCII chars")
    if not (isinstance(sub, str) and len(sub) <= 23 and sub.isascii() and sub.isprintable()):
        die(f"{path}: launcher.subtitle must be <=23 printable ASCII chars")
    for key in ("accent", "accent2"):
        if not (isinstance(launcher.get(key), str) and HEX.match(launcher[key])):
            die(f"{path}: launcher.{key} must be #RRGGBB")
    glyph = launcher.get("glyph", label[0])
    if not (isinstance(glyph, str) and len(glyph) == 1 and glyph.isascii() and glyph.isprintable() and glyph != " "):
        die(f"{path}: launcher.glyph must be one printable ASCII character")
    order = launcher.get("order", 1000)
    if not isinstance(order, int) or isinstance(order, bool) or not 0 <= order <= 100000:
        die(f"{path}: launcher.order must be an integer 0..100000")
    return {"app": name, "label": label, "subtitle": sub, "top": int(launcher["accent"][1:], 16),
            "bottom": int(launcher["accent2"][1:], 16), "glyph": glyph, "order": order}


def main():
    if len(sys.argv) < 4:
        die("usage: gen_app_table.py <output.c> <apps-dir> <app>...")
    out, apps_dir, names = sys.argv[1], sys.argv[2], sys.argv[3:]
    if len(set(names)) != len(names):
        die("duplicate app name")
    items = [i for i in (load(apps_dir, n) for n in names) if i]
    items.sort(key=lambda i: (i["order"], i["app"]))
    if len(items) > 9:
        die("at most 9 apps may appear in the launcher")
    lines = ['/* Generated by tools/gen_app_table.py from the app manifests -- do not edit. */',
             '#include "sand/proc/apps.h"', '',
             '/* SAPP images are converted to linkable objects by the Makefile (objcopy -I binary). */',
             '#define APP_SYMBOLS(id) extern const uint8_t _binary_##id##_sapp_start[]; extern const uint8_t _binary_##id##_sapp_end[];',
             '#define APP_ENTRY(id) { #id, _binary_##id##_sapp_start, _binary_##id##_sapp_end }',
             " ".join(f"APP_SYMBOLS({n})" for n in names),
             'struct app_entry { const char *name; const uint8_t *start; const uint8_t *end; };',
             'static const struct app_entry table[] = {', "    " + ", ".join(f"APP_ENTRY({n})" for n in names), '};',
             '#define APP_COUNT (sizeof(table)/sizeof(table[0]))',
             'static const struct sand_app_launcher_info launchers[] = {']
    for i in items:
        g = i["glyph"]; gl = "'\\\\'" if g == "\\" else ("'\\''" if g == "'" else "'" + g + "'")
        lines.append(f'    {{ {cstr(i["label"])}, {cstr(i["app"])}, {cstr(i["subtitle"])}, 0x{i["top"]:06X}u, 0x{i["bottom"]:06X}u, {gl} }},')
    if not items:
        lines.append('    { "", "", "", 0u, 0u, 0 }')
    lines += ['};', f'#define LAUNCHER_COUNT {len(items)}u', '',
              'int apps_find(const char *name,const uint8_t **image,uint32_t *size) {',
              '    if(name==0 || image==0 || size==0) return -1;',
              '    for(uint32_t i=0;i<APP_COUNT;++i) {',
              '        uint32_t j=0u; while(name[j] && table[i].name[j]==name[j]) ++j;',
              "        if(name[j]=='\\0' && table[i].name[j]=='\\0') { *image=table[i].start; *size=(uint32_t)(table[i].end-table[i].start); return 0; }",
              '    }', '    return -1;', '}',
              'int apps_name_at(uint32_t index,const char **name) {',
              '    if(index>=APP_COUNT || name==0) return -1;', '    *name=table[index].name; return 0;', '}',
              'uint32_t apps_launcher_count(void) { return LAUNCHER_COUNT; }',
              'int apps_launcher_at(uint32_t index,struct sand_app_launcher_info *out) {',
              '    if(index>=LAUNCHER_COUNT || out==0) return -1;', '    *out=launchers[index]; return 0;', '}', '']
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    Path(out).write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
